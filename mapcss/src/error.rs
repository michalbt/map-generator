use cssparser::ParseError;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum MapCssErrorKind {
    ObjectTypeExpected,
    TagKeyExpected,
    TagValueExpected,
    TagNumericValueExpected,
    TagStringValueExpected,
    RegexExpected,
    InvalidRegex,
    TestBlockExpected,
    TagKeyOrExclamationExpected,
    InvalidTokenInsideTest,
    IntegerExpected,
    FloatExpected,
    PercentageExpected,
    FloatOrPercentageExpected,
    InvalidHashColor,
    ColorUnitFloatExpected,
    ColorUnitFloatOutOfRange,
    CommaExpected,
    ColorAlphaUnitFloatExpected,
    ColorAlphaUnitFloatOutOfRange,
    InvalidNamedColor,
    ColorExpected,
    UrlExpected,
    CommaSeparatedIntegerListExpected,
    CommaSeparatedIntegerListTooShort,
    FontWeightExpected,
    InvalidFontWeight,
    FontStyleExpected,
    InvalidFontStyle,
    FontVariantExpected,
    InvalidFontVariant,
    TextDecorationExpected,
    InvalidTextDecoration,
    TextTransformExpected,
    InvalidTextTransform,
    TextPositionExpected,
    InvalidTextPosition,
    PropertyNameExpected,
    UnsupportedPropertyName,
    ColonExpected,
    SemicolonExpected,
    DeclarationBlockExpected,
}

pub type MapCssParseError<'i> = ParseError<'i, MapCssErrorKind>;
